-- Versioniertes Schema (Flyway). Bewusst portables SQL, damit dieselben
-- Migrationen auf PostgreSQL (Betrieb) und H2 im PostgreSQL-Modus (Tests) laufen.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    email         VARCHAR(190) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    supervisor_id BIGINT REFERENCES app_user (id),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_role CHECK (role IN ('EMPLOYEE', 'SUPERVISOR', 'ADMIN'))
);

CREATE TABLE time_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES app_user (id),
    work_date     DATE         NOT NULL,
    start_time    TIME         NOT NULL,
    end_time      TIME         NOT NULL,
    break_minutes INT          NOT NULL DEFAULT 0,
    note          VARCHAR(500),
    status        VARCHAR(30)  NOT NULL,
    version       BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_time_entry_order CHECK (end_time > start_time),
    CONSTRAINT ck_time_entry_break CHECK (break_minutes >= 0)
);
CREATE INDEX ix_time_entry_user_date ON time_entry (user_id, work_date);

CREATE TABLE correction_request (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id         BIGINT       NOT NULL REFERENCES time_entry (id),
    requested_by_id  BIGINT       NOT NULL REFERENCES app_user (id),
    new_start_time   TIME         NOT NULL,
    new_end_time     TIME         NOT NULL,
    new_break_minutes INT         NOT NULL,
    new_note         VARCHAR(500),
    reason           VARCHAR(500) NOT NULL,
    status           VARCHAR(20)  NOT NULL,
    decided_by_id    BIGINT REFERENCES app_user (id),
    decision_comment VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at       TIMESTAMP WITH TIME ZONE,
    version          BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX ix_correction_status ON correction_request (status);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    object_type VARCHAR(40)  NOT NULL,
    object_id   BIGINT,
    action      VARCHAR(40)  NOT NULL,
    actor       VARCHAR(190) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    old_value   VARCHAR(1000),
    new_value   VARCHAR(1000)
);
CREATE INDEX ix_audit_occurred ON audit_log (occurred_at);
