-- Abwesenheiten (Urlaub, Krankheit, Sonstiges)
CREATE TABLE absence (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES app_user (id),
    absence_type     VARCHAR(20)  NOT NULL,
    start_date       DATE         NOT NULL,
    end_date         DATE         NOT NULL,
    note             VARCHAR(500),
    status           VARCHAR(20)  NOT NULL,
    decided_by_id    BIGINT REFERENCES app_user (id),
    decision_comment VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at       TIMESTAMP WITH TIME ZONE,
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_absence_dates CHECK (end_date >= start_date)
);
CREATE INDEX ix_absence_user_dates ON absence (user_id, start_date, end_date);
CREATE INDEX ix_absence_status ON absence (status);
